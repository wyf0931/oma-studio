<script setup lang="ts">
import { toRefs } from "vue";
import { useChat } from "./context";
import { useI18n } from "../../shared/i18n-context";

import OmaIcon from "../../ui/Icon.vue";
const chatFeature = useChat();
const { deleteChatTarget } = toRefs(chatFeature.state);
const { confirmDeleteChat } = chatFeature;
const i18nFeature = useI18n();
const { t } = i18nFeature;
</script>
<template>
  <dialog
    class="modal"
    :open="Boolean(!!deleteChatTarget)"
    v-show="deleteChatTarget"
    @click.self="deleteChatTarget = null"
  >
    <div class="modal-box confirm-box">
      <div class="dialog-head">
        <div>
          <div class="eyebrow" v-text="t('dialogs.deleteChat')"></div>
          <h2 v-text="t('dialogs.removeConversation')"></h2>
        </div>
        <button class="icon-btn" @click="deleteChatTarget = null" :aria-label="t('common.close')">
          <OmaIcon name="x" aria-hidden="true" />
        </button>
      </div>
      <p class="confirm-copy">
        This removes the Pi session and files generated by this chat. The Agent definition will remain.
      </p>
      <div class="dialog-actions">
        <button
          type="button"
          class="btn btn-sm btn-ghost"
          @click="deleteChatTarget = null"
          v-text="t('common.cancel')"
        ></button
        ><button
          type="button"
          class="btn btn-sm btn-error"
          @click="confirmDeleteChat()"
          v-text="t('common.delete')"
        ></button>
      </div>
    </div>
  </dialog>
</template>
