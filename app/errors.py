"""Stable API error codes shared by the backend and frontend."""

import re
from dataclasses import dataclass
from typing import Any


@dataclass(frozen=True)
class ErrorDefinition:
    code: str
    message: str


# Keep this catalog small and stable. The English message is retained in API
# responses for compatibility; clients should translate using ``code``.
