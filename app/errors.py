_EXACT_CODES = {definition.message: code for code, definition in ERROR_CODES.items()}
_DYNAMIC_PATTERNS: tuple[tuple[re.Pattern[str], str, tuple[str, ...]], ...] = (
    (
        re.compile(r"^Skill (.+) is already installed$"),
        "market.skillExists",
        ("skill",),
    ),
    (
        re.compile(r"^Extension (.+) is already installed$"),
        "market.extensionExists",
        ("name",),
    ),
    (re.compile(r"^MCP server (.+) already exists$"), "market.mcpExists", ("name",)),
    (re.compile(r"^Chat (.+) not found$"), "chat.notFound", ("id",)),
)


def classify_error(detail: Any, status_code: int) -> tuple[str, dict[str, Any], str]:
    """Return a stable code, interpolation params, and legacy message."""

    message = str(detail)
    exact = _EXACT_CODES.get(message)
    if exact:
        return exact, {}, message
    for pattern, code, names in _DYNAMIC_PATTERNS:
        match = pattern.match(message)
        if match:
            return code, dict(zip(names, match.groups())), message
    return ("server.error" if status_code >= 500 else "request.invalid"), {}, message


def error_payload(detail: Any, status_code: int) -> dict[str, Any]:
    code, params, message = classify_error(detail, status_code)
    return {"detail": message, "code": code, "params": params}
